from sklearn.feature_selection import f_classif

def select_genes_two_stage(gene_train_df, y_train, variance_top_n=5000, k_final=1000):
    """
    Stage 1: keep the variance_top_n highest-variance genes (fit on train only).
    Stage 2: from those, keep the k_final genes with the highest ANOVA F-statistic
             w.r.t. the class labels (fit on train only).
    Returns the list of selected gene names.
    """
    # Stage 1: variance filter
    gene_variances = gene_train_df.var(axis=0)
    top_variance_genes = gene_variances.nlargest(variance_top_n).index

    # Stage 2: ANOVA F-test on the survivors
    X_stage1 = gene_train_df[top_variance_genes]
    f_scores, p_values = f_classif(X_stage1, y_train)

    f_score_series = pd.Series(f_scores, index=top_variance_genes)
    selected_genes = f_score_series.nlargest(k_final).index.tolist()

    return selected_genes


