def preprocess_pathology_fold(clean_df, banff_cols, train_idx, val_idx):
    """
    Fit median imputation on training rows only, apply to both train and val.
    Adds a missingness indicator column per Banff variable before imputing.
    Returns two DataFrames: processed train and val pathology feature sets.
    """
    train_df = clean_df.loc[train_idx, banff_cols].copy()
    val_df = clean_df.loc[val_idx, banff_cols].copy()

    # Step 1: missingness indicators (built from raw NaN pattern, before imputation)
    for col in banff_cols:
        train_df[f'{col}_was_missing'] = train_df[col].isna().astype(int)
        val_df[f'{col}_was_missing'] = val_df[col].isna().astype(int)

    # Step 2: median imputation, fit on train only
    medians = train_df[banff_cols].median()

    for col in banff_cols:
        train_df[col] = train_df[col].fillna(medians[col])
        val_df[col] = val_df[col].fillna(medians[col])  # note: val uses TRAIN medians, never its own

    return train_df, val_df, medians


