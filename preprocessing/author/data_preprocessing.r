# ============================================================
# CELL 3 — Compatibility implementation of quantable::robustscale
# ============================================================

# This is a local compatibility implementation of the quantable
# robustscale behavior needed by preprocessing.R.
#
# Defaults are retained:
#   dim = 2
#   center = TRUE
#   scale = FALSE
#   preserveScale = TRUE
#
# The authors call robustscale(dataset, dim = 1), so rows/features
# are centered using their row medians.

robustscale <- function(data, dim = 2, center = TRUE, scale = FALSE,
                        preserveScale = TRUE) {

  data <- as.matrix(data)

  if (!dim %in% c(1, 2)) {
    stop("dim must be 1 or 2")
  }

  medians <- NULL

  if (center) {
    if (dim == 1) {
      medians <- apply(data, 1, median, na.rm = TRUE)
      data <- sweep(data, 1, medians, "-")
    } else {
      medians <- apply(data, 2, median, na.rm = TRUE)
      data <- sweep(data, 2, medians, "-")
    }
  }

  mads <- NULL

  if (scale) {
    if (dim == 1) {
      mads <- apply(data, 1, mad, na.rm = TRUE)
      if (preserveScale) {
        mads <- mads / mean(mads, na.rm = TRUE)
      }
      data <- sweep(data, 1, mads, "/")
    } else {
      mads <- apply(data, 2, mad, na.rm = TRUE)
      if (preserveScale) {
        mads <- mads / mean(mads, na.rm = TRUE)
      }
      data <- sweep(data, 2, mads, "/")
    }
  }

  list(
    data = data,
    medians = medians,
    mads = mads
  )
}

