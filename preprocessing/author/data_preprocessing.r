# 1. Load expression data
# ------------------------------------------------------------

loadExpressionData <- function(filename) {

  start_pattern <- "!series_matrix_table_begin"
  end_pattern   <- "!series_matrix_table_end"

  GEO_lines <- readLines(filename, warn = FALSE)

  GEO_start <- grep(start_pattern, GEO_lines)
  GEO_end   <- grep(end_pattern, GEO_lines)

  if (length(GEO_start) != 1) {
    stop("Could not uniquely locate !series_matrix_table_begin")
  }

  if (length(GEO_end) != 1) {
    stop("Could not uniquely locate !series_matrix_table_end")
  }

  GEO_nrows <- GEO_end - GEO_start - 2

  GEO <- read.table(
    filename,
    header = TRUE,
    sep = "",
    skip = GEO_start,
    nrows = GEO_nrows,
    quote = "\"",
    comment.char = "",
    check.names = TRUE,
    stringsAsFactors = FALSE
  )

  GEO$ID_REF <- gsub('"', '', GEO$ID_REF)

  return(GEO)
}


# ------------------------------------------------------------
# 2. Load GEO sample metadata
#
# This follows the authors' intended structure:
#   - sample metadata are read from !Sample_title
#     through the line before !series_matrix_table_begin
#   - first field = metadata variable name
#   - remaining fields = sample values
#   - transpose so samples are rows
#
# The explicit parsing avoids the zero-row problem encountered
# with the original nrows-based implementation on GSE98320.
# ------------------------------------------------------------

loadMetaData <- function(filename) {

  GEO_lines <- readLines(filename, warn = FALSE)

  # Locate metadata block
  start_pattern <- "^!Sample_title"
  end_pattern   <- "^!series_matrix_table_begin"

  meta_start <- grep(start_pattern, GEO_lines)
  meta_end   <- grep(end_pattern, GEO_lines)

  if (length(meta_start) != 1) {
    stop(
      paste0(
        "Could not uniquely locate !Sample_title. ",
        "Found ", length(meta_start), " matches."
      )
    )
  }

  if (length(meta_end) != 1) {
    stop(
      paste0(
        "Could not uniquely locate !series_matrix_table_begin. ",
        "Found ", length(meta_end), " matches."
      )
    )
  }

  if (meta_end <= meta_start) {
    stop("Metadata block boundaries are invalid.")
  }

  # Extract all !Sample_* lines
  meta_lines <- GEO_lines[meta_start:(meta_end - 1)]

  if (length(meta_lines) == 0) {
    stop("No GEO sample metadata lines were found.")
  }

  # ----------------------------------------------------------
  # Parse GEO metadata.
  #
  # sep="" is intentional:
  # GEO values are quoted, so spaces inside quoted values are
  # preserved while whitespace separates fields.
  # ----------------------------------------------------------

  meta_df <- read.table(
    text = meta_lines,
    header = FALSE,
    sep = "",
    quote = "\"",
    fill = TRUE,
    comment.char = "",
    check.names = FALSE,
    stringsAsFactors = FALSE
  )

  if (nrow(meta_df) == 0 || ncol(meta_df) < 2) {
    stop(
      paste0(
        "Metadata parsing failed: ",
        nrow(meta_df), " rows x ",
        ncol(meta_df), " columns."
      )
    )
  }

  # ----------------------------------------------------------
  # First column = metadata field names
  # Remaining columns = samples
  # ----------------------------------------------------------

  field_names <- meta_df[[1]]

  values <- meta_df[, -1, drop = FALSE]

  # Make field names syntactically valid and unique,
  # matching the behavior of the authors' code.
  field_names <- make.names(
    field_names,
    unique = TRUE
  )

  rownames(values) <- field_names

  # ----------------------------------------------------------
  # Transpose:
  #
  # before:
  #   metadata fields x samples
  #
  # after:
  #   samples x metadata fields
  # ----------------------------------------------------------

  meta_df <- as.data.frame(
    t(values),
    stringsAsFactors = FALSE,
    check.names = TRUE
  )

  # ----------------------------------------------------------
  # Confirm sample accession field exists
  # ----------------------------------------------------------

  if (!"X.Sample_geo_accession" %in% colnames(meta_df)) {

    cat("\nERROR: X.Sample_geo_accession was not found.\n\n")

    cat("Parsed metadata columns:\n")
    print(colnames(meta_df))

    cat("\nFirst metadata field names:\n")
    print(head(field_names, 20))

    stop("X.Sample_geo_accession was not found.")
  }

  # ----------------------------------------------------------
  # Use GEO accession as row names
  # This reproduces the authors' original behavior:
  #
  # rownames(meta_df) =
  #     make.names(meta_df$X.Sample_geo_accession, unique=TRUE)
  # ----------------------------------------------------------

  rownames(meta_df) <- make.names(
    meta_df$X.Sample_geo_accession,
    unique = TRUE
  )

  return(meta_df)
}


# ------------------------------------------------------------
# 3. Probe -> gene mapping and median aggregation
# ------------------------------------------------------------

matchAggregate <- function(expression, mapping, id_type) {

  expression$Probe.Set.ID <- expression$ID_REF

  expression_mapped <- left_join(
    expression,
    mapping,
    by = "Probe.Set.ID"
  )

  expression_aggre <- aggregate(
    subset(
      expression_mapped,
      select = -c(ID_REF, Probe.Set.ID)
    ),
    by = list(expression_mapped[[id_type]]),
    FUN = function(x) median(x)
  )

  names(expression_aggre)[
    names(expression_aggre) == "Group.1"
  ] <- id_type

  return(expression_aggre)
}


