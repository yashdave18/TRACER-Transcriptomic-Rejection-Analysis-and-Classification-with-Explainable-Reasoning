getProbeMapping <- function(
  probe_annotation_file,
  identifier_type
) {

  probe_annot <- read.table(
    probe_annotation_file,
    header = TRUE,
    sep = ",",
    skip = 25,
    quote = "\"",
    comment.char = "",
    check.names = FALSE,
    stringsAsFactors = FALSE
  )

  probe_mapping <- probe_annot[
    ,
    c("Probe.Set.ID", identifier_type)
  ]

  probe_mapping <- separate_rows(
    probe_mapping,
    identifier_type,
    sep = " /// "
  )

  return(probe_mapping)
}


# ------------------------------------------------------------
# 5. Combine datasets using shared Entrez genes
# ------------------------------------------------------------

combineDataSets <- function(dataset1, dataset2) {

  shared.genes <- intersect(
    dataset1[["Entrez.Gene"]],
    dataset2[["Entrez.Gene"]]
  )

  dataset1 <- dataset1[
    dataset1[["Entrez.Gene"]] %in% shared.genes,
    ,
    drop = FALSE
  ]

  dataset2 <- dataset2[
    dataset2[["Entrez.Gene"]] %in% shared.genes,
    ,
    drop = FALSE
  ]

  rownames(dataset1) <- dataset1[["Entrez.Gene"]]
  rownames(dataset2) <- dataset2[["Entrez.Gene"]]

  combined.dataset <- cbind(
    dataset1,
    dataset2
  )

  combined.dataset <- combined.dataset[
    ,
    -which(
      names(combined.dataset) %in%
        c(
          "X",
          "Entrez.Gene",
          "ID_REF",
          "Probe.Set.ID"
        )
    ),
    drop = FALSE
  ]

  return(combined.dataset)
}


# ------------------------------------------------------------
# 6. ComBat + robust scaling
#
# quantable::robustscale() is not installed here, so the
# compatibility implementation below reproduces the behavior
# required by the authors' call:
#
#   robustscale(dataset, dim = 1)$data
#
# with center = TRUE and scale = FALSE.
# ------------------------------------------------------------

robustscale <- function(
  data,
  dim = 2,
  center = TRUE,
  scale = FALSE,
  preserveScale = TRUE
) {

  data <- as.matrix(data)

  if (dim == 1) {

    # Scale each column using its median
    if (center) {
      centers <- apply(
        data,
        2,
        median,
        na.rm = TRUE
      )

      data <- sweep(
        data,
        2,
        centers,
        FUN = "-"
      )
    }

    if (scale) {

      scales <- apply(
        data,
        2,
        function(x) {
          mad(
            x,
            center = 0,
            constant = 1,
            na.rm = TRUE
          )
        }
      )

      scales[scales == 0 | is.na(scales)] <- 1

      data <- sweep(
        data,
        2,
        scales,
        FUN = "/"
      )
    }

  } else {

    # Scale each row
    if (center) {
      centers <- apply(
        data,
        1,
        median,
        na.rm = TRUE
      )

      data <- sweep(
        data,
        1,
        centers,
        FUN = "-"
      )
    }

    if (scale) {

      scales <- apply(
        data,
        1,
        function(x) {
          mad(
            x,
            center = 0,
            constant = 1,
            na.rm = TRUE
          )
        }
      )

      scales[scales == 0 | is.na(scales)] <- 1

      data <- sweep(
        data,
        1,
        scales,
        FUN = "/"
      )
    }
  }

  return(
    list(
      data = data
    )
  )
}


# ------------------------------------------------------------
# 7. ComBat + robust scaling of each dataset separately
# ------------------------------------------------------------

normalizeScaleDatasets <- function(
  combined.dataset,
  batch.indication
) {

  combat.combined <- ComBat(
    dat = combined.dataset,
    batch = batch.indication,
    mod = NULL,
    par.prior = TRUE,
    prior.plots = FALSE
  )

  dataset.names <- unique(batch.indication)

  n.datasets <- length(dataset.names)

  datasets <- list()

  for (i in seq_len(n.datasets)) {

    dataset <- combat.combined[
      ,
      which(
        batch.indication == dataset.names[[i]]
      ),
      drop = FALSE
    ]

    dataset.scaled <- robustscale(
      dataset,
      dim = 1
    )$data

    datasets[[i]] <- dataset.scaled
  }

  return(datasets)
}


