# The authors' script expects uncompressed .txt files.
gunzip_if_needed <- function(gzfile, txtfile) {
  if (!file.exists(txtfile)) {
    con_in <- gzfile(gzfile, "rb")
    con_out <- file(txtfile, "wb")
    repeat {
      buf <- readBin(con_in, what = "raw", n = 1024^2)
      if (length(buf) == 0) break
      writeBin(buf, con_out)
    }
    close(con_in)
    close(con_out)
  }
  stopifnot(file.exists(txtfile))
}

